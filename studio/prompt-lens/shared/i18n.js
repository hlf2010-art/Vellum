/** @param {unknown} value */
export function normalizeLocale(value) {
  const v = String(value || "").trim();
  if (v === "en" || v.toLowerCase() === "en-us") return "en";
  if (v === "zh" || v === "zh-CN" || v === "zh-Hans" || v.toLowerCase() === "zh_cn") {
    return "zh-CN";
  }
  return DEFAULT_LOCALE;
}

/** 生成提示词语言：非法值回落英语 */
export function normalizePromptLocale(value) {
  const v = String(value || "").trim();
  if (v === "zh" || v === "zh-CN" || v === "zh-Hans" || v.toLowerCase() === "zh_cn") {
    return "zh-CN";
  }
  return DEFAULT_PROMPT_LOCALE;
}

/** @param {unknown} value @returns {"system"|"light"|"dark"} */
export function normalizeTheme(value) {
  const v = String(value || "").trim().toLowerCase();
  if (v === "light" || v === "dark" || v === "system") return v;
  return DEFAULT_THEME;
}

/**
 * 将偏好解析为实际亮/暗（system 依赖当前环境）
 * @param {unknown} pref
 * @param {boolean} [systemDark]
 * @returns {"light"|"dark"}
 */
export function resolveTheme(pref, systemDark) {
  const p = normalizeTheme(pref);
  if (p === "light" || p === "dark") return p;
  if (typeof systemDark === "boolean") return systemDark ? "dark" : "light";
  if (typeof window !== "undefined" && window.matchMedia) {
    return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  }
  return "light";
}

